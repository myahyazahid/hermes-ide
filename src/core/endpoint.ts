// Endpoint handling. Hermes resolves provider/base_url from config.yaml *before* env
// ("config beats the env"), so env alone cannot redirect it. Two modes therefore exist:
//  - "hermes": use the user's own Hermes config untouched; models are picked per session.
//  - "custom": run Hermes with a dedicated HERMES_HOME whose config.yaml holds base URL and
//    model; the API key travels only through the child's environment, never to disk.
import os from "node:os";
import path from "node:path";

export type EndpointMode = "hermes" | "custom";

export interface CustomEndpoint {
  baseUrl: string;
  model: string;
  apiKey?: string;
  /** 0/undefined = unknown; written as model.context_length so Hermes stops guessing. */
  contextLength?: number;
}

export const MIN_CONTEXT_TOKENS = 64_000;

/**
 * Provider credentials that must not leak into a custom-endpoint Hermes process: the PRD only
 * allows the active profile's key to reach Hermes.
 */
const PROVIDER_ENV_VARS = [
  "OPENAI_API_KEY", "OPENAI_BASE_URL", "OPENROUTER_API_KEY", "OPENROUTER_BASE_URL", "ANTHROPIC_API_KEY",
  "GOOGLE_API_KEY", "GEMINI_API_KEY", "NOUS_API_KEY", "GLM_API_KEY", "KIMI_API_KEY", "MINIMAX_API_KEY",
  "MINIMAX_CN_API_KEY", "HF_TOKEN", "NVIDIA_API_KEY", "XIAOMI_API_KEY", "ARCEEAI_API_KEY", "OLLAMA_API_KEY",
  "DEEPINFRA_API_KEY", "KILOCODE_API_KEY", "AI_GATEWAY_API_KEY", "HERMES_INFERENCE_PROVIDER",
  "HERMES_INFERENCE_MODEL",
];

export function normalizeBaseUrl(url: string): string {
  return url.trim().replace(/\/+$/, "");
}

export function validateCustomEndpoint(ep: CustomEndpoint): string | undefined {
  let parsed: URL;
  try {
    parsed = new URL(normalizeBaseUrl(ep.baseUrl));
  } catch {
    return "invalidUrl";
  }
  if (parsed.protocol !== "http:" && parsed.protocol !== "https:") return "invalidUrl";
  if (!ep.model.trim()) return "missingModel";
  return undefined;
}

/** config.yaml for the dedicated profile. JSON strings are valid YAML double-quoted scalars. */
export function buildProfileConfigYaml(ep: CustomEndpoint): string {
  const lines = [
    "# Generated by Hermes IDE for its Custom API profile. Edit the endpoint from the IDE instead.",
    "model:",
    `  default: ${JSON.stringify(ep.model.trim())}`,
    '  provider: "custom"',
    `  base_url: ${JSON.stringify(normalizeBaseUrl(ep.baseUrl))}`,
  ];
  if (ep.contextLength && ep.contextLength > 0) lines.push(`  context_length: ${Math.floor(ep.contextLength)}`);
  return lines.join("\n") + "\n";
}

export interface LaunchEnvOptions {
  parentEnv: NodeJS.ProcessEnv;
  mode: EndpointMode;
  custom?: CustomEndpoint;
  /** Dedicated HERMES_HOME for custom mode. */
  profileHome?: string;
}

export function buildLaunchEnv(opts: LaunchEnvOptions): NodeJS.ProcessEnv {
  const env: NodeJS.ProcessEnv = { ...opts.parentEnv, PYTHONIOENCODING: "utf-8", PYTHONUTF8: "1" };
  if (opts.mode !== "custom" || !opts.custom) return env;
  for (const key of PROVIDER_ENV_VARS) delete env[key];
  if (opts.profileHome) env.HERMES_HOME = opts.profileHome;
  // Hermes only sends OPENAI_API_KEY to the host OPENAI_BASE_URL names (its own leak guard), so the
  // pair has to match the configured base_url exactly.
  if (opts.custom.apiKey) {
    env.OPENAI_BASE_URL = normalizeBaseUrl(opts.custom.baseUrl);
    env.OPENAI_API_KEY = opts.custom.apiKey;
  }
  return env;
}

export function defaultHermesHome(env: NodeJS.ProcessEnv = process.env, platform: NodeJS.Platform = process.platform): string {
  if (env.HERMES_HOME?.trim()) return env.HERMES_HOME.trim();
  const home = env.USERPROFILE ?? env.HOME ?? os.homedir();
  if (platform === "win32") {
    return path.win32.join(env.LOCALAPPDATA ?? path.win32.join(home, "AppData", "Local"), "hermes");
  }
  return path.posix.join(home, ".hermes");
}

export interface HermesModelConfig {
  provider?: string;
  baseUrl?: string;
  model?: string;
}

/**
 * Reads `model.{default|model, provider, base_url}` from a Hermes config.yaml without a YAML
 * dependency. Only the top-level `model:` mapping is inspected; anything else is ignored.
 */
export function readHermesModelConfig(yaml: string): HermesModelConfig {
  const result: HermesModelConfig = {};
  const lines = yaml.split(/\r?\n/);
  const start = lines.findIndex((l) => /^model\s*:\s*(#.*)?$/.test(l));
  if (start === -1) {
    const inline = lines.find((l) => /^model\s*:\s*\S/.test(l));
    if (inline) result.model = unquote(inline.replace(/^model\s*:\s*/, ""));
    return result;
  }
  for (const line of lines.slice(start + 1)) {
    if (/^\S/.test(line)) break; // next top-level key
    const m = /^ {1,4}(default|model|provider|base_url)\s*:\s*(.*)$/.exec(line);
    if (!m) continue;
    const value = unquote(m[2]);
    if (!value) continue;
    if (m[1] === "provider") result.provider = value;
    else if (m[1] === "base_url") result.baseUrl = value;
    else result.model ??= value;
  }
  return result;
}

function unquote(raw: string): string {
  let v = raw.trim();
  if (v.startsWith('"')) {
    const end = v.indexOf('"', 1);
    return end > 0 ? v.slice(1, end) : v.slice(1);
  }
  if (v.startsWith("'")) {
    const end = v.indexOf("'", 1);
    return end > 0 ? v.slice(1, end) : v.slice(1);
  }
  v = v.replace(/\s+#.*$/, "");
  return v.trim();
}

/** Masks a key for display: "sk-••••••••a91f". */
export function maskKey(key: string | undefined): string {
  if (!key) return "";
  if (key.length <= 8) return "•".repeat(key.length);
  const prefix = key.startsWith("sk-") ? "sk-" : key.slice(0, 2);
  return `${prefix}${"•".repeat(8)}${key.slice(-4)}`;
}

export interface ModelChoice {
  modelId: string;
  name: string;
  description?: string | null;
}

/**
 * Picks the ACP model id for a model name the user typed. Hermes ids look like
 * `custom:router.example.com:customer-service` or `anthropic:claude-x`; exact id wins, then a
 * suffix match on the model name, preferring custom endpoints.
 */
export function resolveModelId(available: ModelChoice[], wanted: string): string | undefined {
  const w = wanted.trim();
  if (!w) return undefined;
  const exact = available.find((m) => m.modelId === w);
  if (exact) return exact.modelId;
  const suffix = available.filter((m) => m.modelId.endsWith(`:${w}`) || m.name === w);
  return (suffix.find((m) => m.modelId.startsWith("custom:")) ?? suffix[0])?.modelId;
}

/**
 * Short label for an ACP model id: `custom:<endpoint>:<model>` → model, `<provider>:<model>` →
 * model. Model names may themselves contain colons (`qwen3:32b`), so only the prefix is cut.
 */
export function shortModelName(modelId: string | undefined, available: ModelChoice[] = []): string {
  if (!modelId) return "";
  const named = available.find((m) => m.modelId === modelId)?.name;
  if (named) return named.split(" · ").pop() ?? named;
  const custom = /^custom:[^:/]+\.[^:/]+:(.+)$/.exec(modelId);
  if (custom) return custom[1];
  const i = modelId.indexOf(":");
  return i >= 0 ? modelId.slice(i + 1) : modelId;
}
