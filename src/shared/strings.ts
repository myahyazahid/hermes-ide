export type Locale = "id" | "en";
export type StringKey = Key;

const tables: Record<Locale, Record<Key, string>> = { id, en };

export function t(locale: Locale, key: StringKey, ...args: (string | number)[]): string {
  const template = tables[locale][key] ?? tables.en[key] ?? key;
  return template.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ""));
}

export function resolveLocale(setting: string | undefined, vscodeLanguage: string): Locale {
  if (setting === "id" || setting === "en") return setting;
  return vscodeLanguage.toLowerCase().startsWith("id") ? "id" : "en";
}
